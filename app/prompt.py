def _knowledge_block(knowledge_dir: Path) -> str:
    files = sorted(
        (p for p in knowledge_dir.rglob("*") if p.is_file()),
        key=lambda p: p.relative_to(knowledge_dir).as_posix(),
    )
    if not files:
        raise FileNotFoundError(f"no knowledge files under {knowledge_dir}")
    return "\n".join(
        f'<doc name="{p.relative_to(knowledge_dir).as_posix()}">\n'
        f"{p.read_bytes().decode('utf-8')}\n</doc>"
        for p in files
    )


def build_system_blocks(knowledge_dir: Path | None = None) -> list[dict]:
    """Return the Messages API ``system`` blocks: behaviour rules, then cached knowledge."""
    root = DEFAULT_KNOWLEDGE_DIR if knowledge_dir is None else Path(knowledge_dir)
    return [
        {"type": "text", "text": BEHAVIOR_RULES},
        {
            "type": "text",
            "text": _knowledge_block(root),
            "cache_control": {"type": "ephemeral"},
        },
    ]
